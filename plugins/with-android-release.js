/**
 * Everything about the Android release build that `app.json` has no key for.
 *
 * This file exists because `android/` is generated: `npx expo prebuild --clean`
 * throws the directory away and writes it again from the Expo template. Before
 * this plugin, the release signing config, the ABI splits and the Android 16
 * resizability opt-out lived as hand edits inside `android/app/build.gradle`,
 * so every SDK upgrade silently reverted them. Now they are re-applied on each
 * prebuild and the generated directory is genuinely disposable.
 *
 * Anything expressible through `expo-build-properties` belongs in `app.json`
 * instead — see the `enableMinifyInReleaseBuilds` / `buildArchs` /
 * `packagingOptions` keys there. Only the gaps are handled here.
 */

const { withAppBuildGradle, withAndroidManifest, AndroidConfig } = require('expo/config-plugins');

/** Marks the block below so repeat prebuilds append it once, not once per run. */
const MARKER = '// @generated by plugins/with-android-release.js';

/**
 * Gradle lets `android { }` be opened more than once — each call configures the
 * same extension. Appending a second block is therefore far more robust than
 * splicing into the template's block with a regex, which breaks whenever the
 * template's formatting shifts under an SDK upgrade. Assignments here run last
 * and win, which is what lets the release `signingConfig` override the debug
 * key the template wires up.
 */
function releaseGradleBlock() {
  return [
    '',
    MARKER,
    '//',
    '// Read `reactNativeArchitectures` rather than hardcoding a list, so this block',
    '// and the `buildArchs` key in app.json can never disagree.',
    'def ivertoAbis() {',
    '    def value = project.getProperties().get("reactNativeArchitectures")',
    '    return value ? value.split(",") : ["armeabi-v7a", "arm64-v8a"]',
    '}',
    '',
    '// True when this invocation was asked for an app bundle. Read from the',
    '// requested task names rather than from a variant, because `splits` is',
    '// configured before any variant exists.',
    'def ivertoBuildingBundle = gradle.startParameter.taskNames.any {',
    '    it.toLowerCase().contains("bundle")',
    '}',
    '',
    'android {',
    '    defaultConfig {',
    '        // `reactNativeArchitectures` only governs what gets *compiled from',
    '        // source*. Prebuilt .so files inside dependency AARs ignore it, so',
    '        // without this filter every x86/x86_64 library still gets merged in —',
    '        // roughly 27 MB of emulator-only payload in the universal APK.',
    '        ndk {',
    '            abiFilters(*ivertoAbis())',
    '        }',
    '    }',
    '',
    '    signingConfigs {',
    '        // Real upload key. The credentials live in the *user-level*',
    '        // ~/.gradle/gradle.properties (%USERPROFILE%\\.gradle\\gradle.properties),',
    '        // never in this repo, and the keystore itself sits outside `android/`',
    '        // so `prebuild --clean` cannot delete it.',
    '        //',
    '        // When the properties are absent — a fresh clone, CI without the',
    '        // secrets — this stays empty and the release build falls back to the',
    '        // debug key below, so the build still works; it just is not',
    '        // publishable.',
    '        release {',
    "            if (project.hasProperty('IVERTO_UPLOAD_STORE_FILE')) {",
    '                storeFile file(IVERTO_UPLOAD_STORE_FILE)',
    '                storePassword IVERTO_UPLOAD_STORE_PASSWORD',
    '                keyAlias IVERTO_UPLOAD_KEY_ALIAS',
    '                keyPassword IVERTO_UPLOAD_KEY_PASSWORD',
    '            }',
    '        }',
    '    }',
    '',
    '    buildTypes {',
    '        release {',
    "            signingConfig (project.hasProperty('IVERTO_UPLOAD_STORE_FILE')",
    '                ? signingConfigs.release',
    '                : signingConfigs.debug)',
    '        }',
    '    }',
    '',
    '    // Emit one APK per CPU architecture instead of a single fat APK carrying',
    '    // every ABI. A device only ever needs its own, so this is the largest size',
    '    // win after switching from debug to release. `universalApk` additionally',
    '    // emits an all-ABI APK for when you want one file that installs anywhere.',
    '    //',
    '    // Off for an app bundle, and it has to be: resource shrinking runs once',
    '    // per split and `buildReleasePreBundle` accepts exactly one',
    '    // shrunk-resources file, so the two together fail the build outright on',
    '    // AGP 8.9+ with "Multiple shrunk-resources files found". Nothing is lost —',
    '    // Play performs its own ABI splitting from the AAB, so splits would be',
    '    // redundant work even where they are tolerated.',
    '    //',
    '    // Consequence worth knowing: `gradlew assembleRelease bundleRelease` in',
    '    // one invocation sees a bundle task and turns splits off for both, so the',
    '    // per-ABI APKs do not appear. Run the two separately when you want both.',
    '    splits {',
    '        abi {',
    '            enable !ivertoBuildingBundle',
    '            reset()',
    '            include(*ivertoAbis())',
    '            universalApk true',
    '        }',
    '    }',
    '}',
    '',
    '// Give each split APK its own versionCode so they can coexist and so a device',
    '// cannot sidegrade from arm64 to armeabi-v7a. Ordered lowest-to-highest by',
    '// device capability; the universal APK keeps the base versionCode.',
    '//',
    '// Uses the `androidComponents` variant API rather than the older',
    '// `android.applicationVariants`, which AGP 8 deprecates and AGP 9 removes.',
    "def ivertoAbiVersionCodes = ['armeabi-v7a': 1, 'x86': 2, 'arm64-v8a': 3, 'x86_64': 4]",
    '',
    'androidComponents {',
    '    onVariants(selector().all()) { variant ->',
    '        variant.outputs.each { output ->',
    '            def abi = output.filters.find {',
    '                it.filterType == com.android.build.api.variant.FilterConfiguration.FilterType.ABI',
    '            }?.identifier',
    '            if (abi != null) {',
    '                def base = variant.outputs.find { it.filters.isEmpty() }?.versionCode?.getOrNull()',
    '                    ?: android.defaultConfig.versionCode',
    '                output.versionCode.set(base * 10 + (ivertoAbiVersionCodes[abi] ?: 0))',
    '            }',
    '        }',
    '    }',
    '}',
    '',
  ].join('\n');
}

const withReleaseGradle = (config) =>
  withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== 'groovy') {
      throw new Error('with-android-release expects a Groovy android/app/build.gradle');
    }
    if (config.modResults.contents.includes(MARKER)) return config;
    config.modResults.contents += releaseGradleBlock();
    return config;
  });

/**
 * Android 16 ignores `android:screenOrientation` and resizability limits on
 * displays wider than 600dp for apps targeting API 36. This app is portrait-only
 * by design, so opt back out to keep behaviour identical to the API 35 build.
 *
 * The opt-out is honoured until targetSdk 37 — making the UI genuinely adaptive
 * is the real fix, and this buys one release cycle for it.
 */
const RESIZABILITY_PROPERTY = 'android.window.PROPERTY_COMPAT_ALLOW_RESTRICTED_RESIZABILITY';

const withRestrictedResizability = (config) =>
  withAndroidManifest(config, (config) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    application.property = (application.property ?? []).filter(
      (item) => item.$?.['android:name'] !== RESIZABILITY_PROPERTY
    );
    application.property.push({
      $: { 'android:name': RESIZABILITY_PROPERTY, 'android:value': 'true' },
    });
    return config;
  });

module.exports = (config) => withRestrictedResizability(withReleaseGradle(config));
